export const AIRPORTS: Airport[] = LIST.map(([code, city, name]) => ({ code, city, name }));

const byCode = new Map(AIRPORTS.map((a) => [a.code, a]));
export const airportOf = (code: string) => byCode.get(code.trim().toUpperCase()) ?? null;

/** 도시·공항 이름(한글)이나 코드로 찾기. 코드가 딱 맞거나 이름이 앞에서부터 맞는 것 먼저 */
export function findAirports(query: string, limit = 6): Airport[] {
  const q = query.trim().replace(/\s/g, '');
  if (!q) return [];
  const upper = q.toUpperCase();
  const score = (a: Airport) => {
    if (a.code === upper) return 0;
    if (a.city.startsWith(q) || a.name.startsWith(q)) return 1;
    if (a.code.startsWith(upper)) return 2;
    if (a.city.includes(q) || a.name.includes(q)) return 3;
    return 9;
  };
  return AIRPORTS.map((a) => [score(a), a] as const)
    .filter(([s]) => s < 9)
    .sort((x, y) => x[0] - y[0])
    .slice(0, limit)
    .map(([, a]) => a);
}
